"""Phones paired with KDE Connect (Linux, Windows, macOS).

KDE Connect keeps its state in Qt's generic config location:
``~/.config/kdeconnect`` (Linux), ``%LOCALAPPDATA%\\kdeconnect`` (Windows),
``~/Library/Preferences/kdeconnect`` (macOS). ``trusted_devices`` is an INI
file with one group per paired device id holding its name, type
(phone/tablet/...), protocol version and the device's own certificate;
``config`` holds this computer's name. Each paired device also gets a
``<device id>/`` folder with per-plugin settings.

Each paired device's certificate was generated by the KDE Connect app on
that device, and every app version writes a recognisable validity period
(read from the source code of each app and its git history):

* kdeconnect-android 1.32+: notBefore = local day - 1 year, notAfter =
  local day + 10 years, both at local midnight; serial 1.
* kdeconnect-android 1.15-1.31: notBefore = local day - 1 year, notAfter =
  notBefore + 10 years, both at local midnight.
* kdeconnect-android 1.0-1.14: notBefore = now - 1 year, notAfter =
  notBefore + 10 years (to the second).
* kdeconnect-ios: notBefore = now - 365 days, notAfter = now + 3650 days
  (to the second); serial 10.
* KDE Connect desktop (kdeconnect-kde): the same 365/3650-day shape with a
  random 160-bit serial.

A certificate with one of these shapes reveals when the app created its
identity on the device, and which app (so which phone OS) made it. This is
an inference from source code and is labelled as such in the output. For
midnight-based shapes the day is exact but 28 February in a leap year may
also mean 29 February (Java maps 29 February minus one year to 28 February).
"""

from __future__ import annotations

import configparser
from datetime import datetime, timedelta
from typing import Any

from ..model import Channel, IdKind, Observation, Validation, ident
from ..plugin import UNRECOGNISED, Context, Plugin, register
from ..readers.x509 import parse_pem_or_der
from ..timeutil import from_unix

_REFS = [
    "https://github.com/KDE/kdeconnect-kde/blob/master/core/kdeconnectconfig.cpp (config locations)",
    "https://github.com/KDE/kdeconnect-kde/blob/master/core/sslhelper.cpp (desktop certificate validity)",
    "https://github.com/KDE/kdeconnect-android/blob/master/src/main/java/org/kde/kdeconnect/helpers/security/"
    "SslHelper.kt (Android certificate validity; history: commits 7fec58d6b, 03b61f7d, 46ad0c62)",
    "https://github.com/KDE/kdeconnect-ios/blob/master/KDE%20Connect/ObjC%20Backend/CertificateServiceHelper.m "
    "(iOS certificate validity)",
]
_CLASSES = {"phone": "phone", "tablet": "tablet", "desktop": "computer", "laptop": "computer", "tv": "other"}


def _qsettings_value(raw: str) -> str:
    """Undo QSettings INI quoting/escaping for string values."""
    v = raw.strip()
    if len(v) >= 2 and v[0] == v[-1] == '"':
        v = v[1:-1]
    return v.replace("\\n", "\n").replace('\\"', '"').replace("\\\\", "\\")


_GEN_ANDROID_132 = "kdeconnect-android 1.32+ (notBefore = day - 1 year, notAfter = day + 10 years)"
_GEN_ANDROID_115 = "kdeconnect-android 1.15-1.31 (notBefore = day - 1 year, notAfter = notBefore + 10 years)"
_GEN_ANDROID_10 = "kdeconnect-android 1.0-1.14 (notBefore = now - 1 year, notAfter = notBefore + 10 years)"
_GEN_IOS = "kdeconnect-ios (notBefore = now - 365 days, notAfter = now + 3650 days, serial 10)"
_GEN_DESKTOP = "KDE Connect desktop (notBefore = now - 365 days, notAfter = now + 3650 days, random serial)"


def _add_years(d: datetime, n: int) -> datetime:
    """Calendar years, as Java's LocalDate.plusYears and Calendar.add do: 29 February becomes 28 February."""
    try:
        return d.replace(year=d.year + n)
    except ValueError:
        return d.replace(year=d.year + n, day=28)


def _is_leap(year: int) -> bool:
    return year % 4 == 0 and (year % 100 != 0 or year % 400 == 0)


def _identity_created(not_before: datetime | None, not_after: datetime | None,
                      serial: str = "") -> dict[str, Any] | None:
    """When and by which KDE Connect app a device certificate was generated, from its validity shape.

    Returns {created, generator, precision ("day" or "second"), phone_os,
    local_day, note} or None when the certificate has none of the known shapes.
    """
    if not (not_before and not_after):
        return None
    span = not_after - not_before
    if abs(span - timedelta(days=4015)) <= timedelta(seconds=2):  # -365 days / +3650 days, to the second
        ios = serial.lstrip("0").lower() == "a"
        return {"created": not_before + timedelta(days=365), "generator": _GEN_IOS if ios else _GEN_DESKTOP,
                "precision": "second", "phone_os": "ios" if ios else None, "local_day": None, "note": None}
    tolerance = timedelta(hours=2)  # local wall-clock bounds converted to UTC: allow for a DST shift
    if not_before.second == 0 and not_before.microsecond == 0 and not_before.minute % 15 == 0:
        # Local midnight written as UTC: the time of day gives the device's UTC offset.
        minutes = -(not_before.hour * 60 + not_before.minute) % 1440
        if minutes > 13 * 60:
            minutes -= 1440
        offset = timedelta(minutes=minutes)
        local_nb = not_before + offset
        day = _add_years(local_nb, 1)
        for local_after, generator in ((_add_years(day, 10), _GEN_ANDROID_132),
                                       (_add_years(local_nb, 10), _GEN_ANDROID_115)):
            if abs(local_after - offset - not_after) <= tolerance:
                note = None
                if day.month == 2 and day.day == 28 and _is_leap(day.year):
                    note = "the identity may have been created on 28 or 29 February (indistinguishable)"
                return {"created": day - offset, "generator": generator, "precision": "day", "phone_os": "android",
                        "local_day": day.date().isoformat(), "note": note,
                        "utc_offset_assumed": f"{'+' if minutes >= 0 else '-'}{abs(minutes) // 60:02d}:"
                                              f"{abs(minutes) % 60:02d}"}
    if abs(_add_years(not_before, 10) - not_after) <= tolerance:
        created = _add_years(not_before, 1)
        note = None
        if created.month == 2 and created.day in (27, 28, 29) and _is_leap(created.year):
            note = "the identity may have been created on 28 or 29 February (indistinguishable)"
        return {"created": created, "generator": _GEN_ANDROID_10, "precision": "second", "phone_os": "android",
                "local_day": None, "note": note}
    return None


def _parse(ctx: Context, base_dirs) -> None:
    for _user, base in base_dirs:
        trusted = ctx.fs.child(base, "trusted_devices")
        cfg_path = ctx.fs.child(base, "config")
        host_name = None
        if cfg_path and cfg_path.is_file():
            with ctx.file_scope(cfg_path):
                cp = configparser.ConfigParser(interpolation=None, strict=False)
                cp.optionxform = str
                cp.read_string(ctx.read_text(cfg_path))
                if cp.has_option("General", "name"):
                    host_name = _qsettings_value(cp["General"]["name"])
                ctx.cover(cfg_path, "parsed", 0, note=f"this computer's KDE Connect name: {host_name}")
        if not trusted or not trusted.is_file():
            continue
        with ctx.file_scope(trusted) as n:
            cp = configparser.ConfigParser(interpolation=None, strict=False)
            cp.optionxform = str
            try:
                cp.read_string(ctx.read_text(trusted))
            except configparser.Error as exc:
                ctx.cover(trusted, UNRECOGNISED, note=f"not an INI file: {exc}")
                continue
            for dev_id in cp.sections():
                sec = cp[dev_id]
                name = _qsettings_value(sec.get("name", ""))
                dtype = _qsettings_value(sec.get("type", "")).lower() or None
                cert = parse_pem_or_der(_qsettings_value(sec.get("certificate", "")).encode())
                dev_dir = ctx.fs.child(base, dev_id)
                plugins = sorted(p.name for p in dev_dir.iterdir() if p.is_dir()) if dev_dir and dev_dir.is_dir() else []
                ids = [ident(IdKind.APP_DEVICE_ID, f"kdeconnect:{dev_id}"), ident(IdKind.DEVICE_NAME, name)]
                data = {
                    "device_id": dev_id, "name": name, "type": dtype,
                    "protocol_version": _qsettings_value(sec.get("protocolVersion", "")) or None,
                    "this_computer_name": host_name, "plugin_folders": plugins,
                    "certificate_not_before": cert.not_before.isoformat() if cert and cert.not_before else None,
                    "certificate_not_after": cert.not_after.isoformat() if cert and cert.not_after else None,
                    "certificate_cn": cert.subject_cn if cert else None,
                }
                device_class = _CLASSES.get(dtype or "", "other" if dtype else None)
                identity = _identity_created(cert.not_before, cert.not_after, cert.serial) if cert else None
                if identity:
                    data.update({"identity_generator": identity["generator"],
                                 "identity_precision": identity["precision"],
                                 "identity_local_day": identity["local_day"],
                                 "identity_utc_offset_assumed": identity.get("utc_offset_assumed"),
                                 "identity_note": identity["note"]})
                # The certificate shape says which app made it; the device type alone does not give the OS.
                phone_os = identity["phone_os"] if identity and device_class in ("phone", "tablet") else None
                label = f"KDE Connect {dtype or 'device'} \"{name or dev_id}\""
                if identity:
                    precise = identity["precision"] == "second"
                    ctx.emit(Observation(
                        artifact=ctx.plugin.id, event="kdeconnect_identity_created",
                        message=f"{label}: KDE Connect identity created on the device by {identity['generator']}",
                        channel=Channel.COMPANION_APP, timestamp=identity["created"],
                        timestamp_desc=("Device certificate generation time (inferred from its validity period, "
                                        "per KDE Connect source code)" if precise else
                                        "Device certificate generation day (notBefore + 1 year, per KDE Connect "
                                        "source code; day precision, device-local midnight)"),
                        provenance=ctx.prov(trusted, f"ini:[{dev_id}].certificate"),
                        device_ids=ids, data=data, phone_os=phone_os, device_class=device_class,
                    ))
                ctx.emit(Observation(
                    artifact=ctx.plugin.id, event="kdeconnect_paired",
                    message=f"{label} is paired (trusted) with this computer",
                    channel=Channel.COMPANION_APP,
                    timestamp=from_unix(dev_dir.stat().st_mtime) if dev_dir else None,
                    timestamp_desc="Device config folder modified (filesystem time)" if dev_dir else "",
                    time_source="filesystem",
                    provenance=ctx.prov(trusted, f"ini:[{dev_id}]"),
                    device_ids=ids, data=data, phone_os=phone_os, device_class=device_class,
                ))
                n[0] += 1


@register
class LinuxKdeConnect(Plugin):
    id = "linux_kdeconnect"
    name = "KDE Connect paired devices"
    os = "linux"
    channel = Channel.COMPANION_APP
    description = __doc__ or ""
    paths = ["home/*/.config/kdeconnect/trusted_devices", "home/*/.config/kdeconnect/config"]
    references = _REFS
    validation = Validation.SYNTHETIC

    def run(self, ctx: Context) -> None:
        _parse(ctx, ctx.user_dirs(".config/kdeconnect"))


