"""Phones connected to a Windows computer over USB (SYSTEM\\Enum\\USB and WPD).

One physical phone appears as several device nodes that share a
ContainerID: the composite parent ``USB\\VID_xxxx&PID_yyyy\\<serial>`` and
interface children (MTP, PTP, ADB, RNDIS tethering) whose descriptions often
carry the marketing model (e.g. ``SM-G900V``). Windows 8 and later store
per-device timestamps as device properties under
``Properties\\{83da6326-97a6-4088-9453-a1923f573b29}``: 0064 install date,
0065 first install date, 0066 last arrival, 0067 last removal.

For an iPhone the USB serial is the device UDID; for Android it is the
``ro.serialno`` value that adb also reports. Instance ids containing ``&``
are generated by Windows when a device reports no serial and are not used as
identifiers.

Phones are recognised by interface signals (Apple mobile-device product ids,
MTP/PTP class, ADB or RNDIS interfaces, or a phone-only vendor), not by
vendor id alone: vendors such as Samsung also make storage and monitors.
"""

from __future__ import annotations

import re
from collections import defaultdict
from dataclasses import dataclass, field

from ..model import Channel, IdKind, Observation, Validation, ident
from ..plugin import Context, Plugin, register
from ..readers.registry import RegKey
from ._windows import SYSTEM_HIVE, key_locator, reg_text, reg_time, system_hive

_DEVPROP_TIMES = "{83da6326-97a6-4088-9453-a1923f573b29}"
_TIME_PROPS = [
    ("0065", "usb_first_install", "First Install Date"),
    ("0064", "usb_install", "Install Date"),
    ("0066", "usb_last_arrival", "Last Arrival Date"),
    ("0067", "usb_last_removal", "Last Removal Date"),
]

APPLE_VID = "05AC"
# Vendors that make (almost) only phones/tablets over USB.
PHONE_VENDORS = {
    "2717": "Xiaomi", "2A70": "OnePlus", "22B8": "Motorola", "22D9": "OPPO/realme",
    "2D95": "vivo", "2AE5": "Fairphone", "2E04": "HMD (Nokia)", "1BBB": "TCL/Alcatel",
    "12D1": "Huawei", "0BB4": "HTC",
}
# Vendors that make phones and other USB devices: need an interface signal.
MIXED_VENDORS = {
    "18D1": "Google", "04E8": "Samsung", "1004": "LG", "0FCE": "Sony", "19D2": "ZTE",
    "17EF": "Lenovo", "0B05": "ASUS", "05C6": "Qualcomm", "0E8D": "MediaTek",
}
_GENERIC_NAMES = {
    "apple iphone", "apple ipad", "iphone", "ipad", "apple mobile device usb composite device",
    "apple mobile device usb device", "android", "mtp usb device", "adb interface",
    "android adb interface", "android composite adb interface", "usb composite device",
    "samsung mobile usb composite device", "samsung android phone", "mobile phone",
}
_VIDPID = re.compile(r"VID_([0-9A-F]{4})&PID_([0-9A-F]{4})", re.I)


def _strip_inf(text: str | None) -> str | None:
    """'@oem26.inf,%desc%;SAMSUNG Mobile USB Composite Device' -> the display text."""
    if not text:
        return None
    if text.startswith("@") and ";" in text:
        text = text.split(";", 1)[1]
    return text.strip() or None


def _signals(key: RegKey) -> set[str]:
    ids = []
    for name in ("HardwareID", "CompatibleIDs"):
        v = key.get(name)
        if isinstance(v, list):
            ids += [str(x).upper() for x in v]
        elif isinstance(v, str):
            ids.append(v.upper())
    text = " ".join(ids + [str(key.get("Service") or "").upper(),
                           str(_strip_inf(key.get("DeviceDesc")) or "").upper()])
    out = set()
    if "MS_COMP_MTP" in text or "WUDFWPDMTP" in text or " MTP" in f" {text}":
        out.add("mtp")
    if "CLASS_06" in text:
        out.add("ptp")
    if "CLASS_FF&SUBCLASS_42&PROT_01" in text or "ADB" in text:
        out.add("adb")
    # RNDIS tethering is class E0/01/03 or EF/04/01. Plain class E0 is any wireless
    # controller: E0/01/01 is a Bluetooth radio (seen on a real VMware hive).
    if ("MS_COMP_RNDIS" in text or "CLASS_E0&SUBCLASS_01&PROT_03" in text
            or "CLASS_EF&SUBCLASS_04&PROT_01" in text or "RNDIS" in text):
        out.add("rndis")
    if "ANDROID" in text:
        out.add("android")
    if "APPLE MOBILE DEVICE" in text or "USBAAPL" in text:
        out.add("apple_mobile")
    return out


def is_ios_pid(pid: str) -> bool:
    try:
        n = int(pid, 16)
    except ValueError:
        return False
    return 0x1290 <= n <= 0x12AF  # iPhone/iPad/iPod touch mobile-device product ids


@dataclass
class _Container:
    vid: str = ""
    pid: str = ""
    serial: str | None = None
    keys: list[RegKey] = field(default_factory=list)
    signals: set[str] = field(default_factory=set)
    names: list[str] = field(default_factory=list)
    models: list[str] = field(default_factory=list)
    interfaces: list[str] = field(default_factory=list)
    mfg: str | None = None


def _real_serial(instance: str) -> str | None:
    if "&" in instance or not instance:
        return None
    return instance


@register
class WindowsUSBPhones(Plugin):
    id = "win_usb_phones"
    name = "Phones connected over USB (device enumeration)"
    os = "windows"
    channel = Channel.USB
    description = __doc__ or ""
    paths = [SYSTEM_HIVE]
    references = [
        "https://learn.microsoft.com/en-us/windows-hardware/drivers/install/devpkey-device-installdate",
        "https://learn.microsoft.com/en-us/windows-hardware/drivers/install/container-ids",
        "https://www.13cubed.com/downloads/windows_registry_cheat_sheet.pdf",
    ]
    validation = Validation.PUBLIC_SAMPLE

    def run(self, ctx: Context) -> None:
        with system_hive(ctx) as opened:
            if opened is None:
                return
            hive, path, control_sets = opened
            hive_rel = ctx.fs.rel(path)
            with ctx.file_scope(path) as n:
                cs = control_sets[0] if control_sets else "\\ControlSet001"
                containers: dict[str, _Container] = defaultdict(_Container)
                for dev_key in hive.subkeys(f"{cs}\\Enum\\USB"):
                    m = _VIDPID.search(dev_key.name)
                    if not m:
                        continue
                    vid, pid = m.group(1).upper(), m.group(2).upper()
                    is_parent = dev_key.name.upper() == f"VID_{vid}&PID_{pid}"
                    for inst in hive.subkeys(dev_key.path):
                        cid = (reg_text(inst.get("ContainerID")) or f"noc:{inst.path}").lower()
                        c = containers[cid]
                        c.keys.append(inst)
                        c.vid, c.pid = c.vid or vid, c.pid or pid
                        sig = _signals(inst)
                        c.signals |= sig
                        if is_parent and _real_serial(inst.name):
                            c.serial = inst.name
                        c.mfg = c.mfg or _strip_inf(reg_text(inst.get("Mfg")))
                        desc = _strip_inf(reg_text(inst.get("DeviceDesc")))
                        friendly = reg_text(inst.get("FriendlyName"))
                        if desc:
                            c.interfaces.append(desc)
                        # Only the media (MTP/PTP) interface describes the handset itself;
                        # other interfaces carry driver descriptions such as "Modem".
                        if not is_parent and {"mtp", "ptp"} & sig:
                            if desc and desc.lower() not in _GENERIC_NAMES:
                                c.models.append(desc)
                            if friendly and friendly.lower() not in _GENERIC_NAMES:
                                c.names.append(friendly)
                # WPD nodes carry the friendly name Windows shows for MTP devices.
                for wpd in hive.walk(f"{cs}\\Enum\\SWD\\WPDBUSENUM", max_depth=1):
                    cid = (reg_text(wpd.get("ContainerID")) or "").lower()
                    if cid and cid in containers:
                        containers[cid].keys.append(wpd)
                        fn = reg_text(wpd.get("FriendlyName"))
                        if fn and fn.lower() not in _GENERIC_NAMES:
                            containers[cid].names.append(fn)

                for cid, c in containers.items():
                    kind = self._classify(c)
                    if kind is None:
                        continue
                    phone_os, device_class = kind
                    serial = c.serial
                    ids = [ident(IdKind.USB_SERIAL, serial)]
                    if phone_os == "ios" and serial:
                        ids.append(ident(IdKind.UDID, serial))
                    if not cid.startswith("noc:") and serial:
                        # ContainerIDs are unique; tie them to the serial within this system.
                        ids.append(ident(IdKind.APP_DEVICE_ID, f"win_container:{cid}"))
                    model = next(iter(c.models), None)
                    name = next((nm for nm in c.names
                                 if not (model and nm.upper().endswith(model.upper()))), None)
                    if model:
                        ids.append(ident(IdKind.MODEL, model))
                    if name and name != model:
                        ids.append(ident(IdKind.DEVICE_NAME, name))
                    vendor = (PHONE_VENDORS.get(c.vid) or MIXED_VENDORS.get(c.vid)
                              or ("Apple" if c.vid == APPLE_VID else None))
                    data = {
                        "vid": c.vid, "pid": c.pid, "vendor": vendor, "manufacturer": c.mfg,
                        "serial": serial, "container_id": None if cid.startswith("noc:") else cid,
                        "signals": sorted(c.signals), "names": sorted(set(c.names)),
                        "models": sorted(set(c.models)),
                        "interfaces": sorted(set(c.interfaces)),
                        "device_keys": [k.path for k in c.keys],
                    }
                    label = name or model or vendor or f"VID_{c.vid}&PID_{c.pid}"
                    # Every interface node records near-identical times. Emit one event per
                    # time type for the phone, from the node holding the decisive value
                    # (earliest install, latest arrival/removal); keep all in the data.
                    per_node: dict[str, list[tuple]] = defaultdict(list)
                    for k in c.keys:
                        for sub, event, desc in _TIME_PROPS:
                            pk = hive.key(f"{k.path}\\Properties\\{_DEVPROP_TIMES}\\{sub}")
                            ts = reg_time(pk.get("(default)")) if pk else None
                            if ts is not None:
                                per_node[event].append((ts, pk, desc))
                    data["node_times"] = {
                        ev: sorted({f"{t.isoformat()} {pk.path}" for t, pk, _d in items})
                        for ev, items in per_node.items()
                    }
                    emitted = 0
                    for _sub, event, desc in _TIME_PROPS:
                        items = per_node.get(event)
                        if not items:
                            continue
                        pick = min if event in ("usb_first_install", "usb_install") else max
                        ts, pk, _d = pick(items, key=lambda t: t[0])
                        ctx.emit(Observation(
                            artifact=self.id, event=event,
                            message=f"USB {device_class} {label}: {desc}",
                            channel=Channel.USB, timestamp=ts, timestamp_desc=desc,
                            provenance=ctx.prov(path, key_locator(hive_rel, pk, "(default)")),
                            device_ids=ids, data=data, phone_os=phone_os, device_class=device_class,
                        ))
                        emitted += 1
                    if not emitted:
                        k = c.keys[0]
                        ctx.emit(Observation(
                            artifact=self.id, event="usb_device_key_last_written",
                            message=f"USB {device_class} {label}: device key last written",
                            channel=Channel.USB, timestamp=k.last_written,
                            timestamp_desc="Registry key last written",
                            provenance=ctx.prov(path, key_locator(hive_rel, k)),
                            device_ids=ids, data=data, phone_os=phone_os, device_class=device_class,
                        ))
                        emitted = 1
                    n[0] += emitted

    @staticmethod
    def _classify(c: _Container) -> tuple[str | None, str] | None:
        if c.vid == APPLE_VID:
            if is_ios_pid(c.pid) or "apple_mobile" in c.signals:
                names = " ".join(c.names + c.models).lower()
                return "ios", "tablet" if "ipad" in names else "phone"
            return None
        android_signal = {"adb", "android", "rndis"} & c.signals
        if c.vid in PHONE_VENDORS:
            return "android", "phone"
        if c.vid in MIXED_VENDORS and (android_signal or "mtp" in c.signals):
            return "android", "phone"
        if android_signal:
            return "android", "phone"
        if "mtp" in c.signals:
            return None if not c.names and not c.models else (None, "other")
        return None
