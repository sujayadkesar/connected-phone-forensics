"""Generate collection targets and documentation from plugin metadata.

Every plugin declares the paths it reads, so the files an examiner must
collect for Connected Phone Forensics are always in sync with what Connected Phone Forensics can parse.
"""

from __future__ import annotations

import uuid
from collections import defaultdict

from .plugin import load_plugins

_NS = uuid.UUID("6f3a1c52-3d1e-4c63-9a55-2f1f2f0b7e11")


def _split(pattern: str) -> tuple[list[str], str | None, bool]:
    """Split a plugin path pattern into (directory parts, file mask, recursive)."""
    parts = [p for p in pattern.replace("\\", "/").split("/") if p]
    if parts and parts[-1] == "**":
        return parts[:-1], None, True
    if "**" in parts:
        i = parts.index("**")
        return parts[:i], parts[-1] if i < len(parts) - 1 else None, True
    mask = parts[-1] if parts else None
    return parts[:-1], mask, False


def _with_sidecars(mask: str | None) -> str | None:
    # A trailing '*' also collects SQLite -wal/-shm files and registry .LOG1/.LOG2.
    if mask and not mask.endswith("*"):
        return mask + "*"
    return mask


def _all_paths() -> dict[str, list[tuple[str, str]]]:
    by_os: dict[str, list[tuple[str, str]]] = defaultdict(list)
    for cls in load_plugins().values():
        for p in cls.paths:
            by_os[cls.os].append((cls.id, p))
    return by_os


def render_targets(fmt: str) -> str:
    by_os = _all_paths()
    if fmt == "list":
        lines = []
        for os_name in sorted(by_os):
            lines.append(f"# {os_name}")
            for pid, p in sorted(set(by_os[os_name]), key=lambda t: t[1]):
                lines.append(f"{p}\t# {pid}")
        return "\n".join(lines)
    if fmt == "kape":
        out = [
            "Description: Connected Phone Forensics - phone-to-computer artifacts",
            "Author: Connected Phone Forensics (generated by 'cpf targets --format kape')",
            "Version: 1.0",
            f"Id: {uuid.uuid5(_NS, 'cpf-kape')}",
            "RecreateDirectories: true",
            "Targets:",
        ]
        seen = set()
        for pid, p in sorted(set(by_os.get("windows", [])), key=lambda t: t[1]):
            dirs, mask, recursive = _split(p)
            win_dirs = ["%user%" if (i == 1 and d == "*" and dirs[0].lower() == "users") else d
                        for i, d in enumerate(dirs)]
            path = "C:\\" + "\\".join(win_dirs)
            key = (path, mask, recursive)
            if key in seen:
                continue
            seen.add(key)
            out += ["    -", f"        Name: CPF - {pid}", "        Category: CPF",
                    f"        Path: {path}"]
            if mask and not recursive:
                out.append(f"        FileMask: '{_with_sidecars(mask)}'")
            elif mask:
                out.append(f"        FileMask: '{mask}'")
            if recursive:
                out.append("        Recursive: true")
        return "\n".join(out)
    if fmt == "velociraptor":
        docs = []
        for os_name, root in (("windows", "C:"), ("macos", "/"), ("linux", "/")):
            globs = []
            for _pid, p in sorted(set(by_os.get(os_name, [])), key=lambda t: t[1]):
                dirs, mask, recursive = _split(p)
                sep = "\\" if os_name == "windows" else "/"
                g = sep.join(dirs)
                if recursive:
                    g += sep + "**" + (sep + mask if mask else "")
                elif mask:
                    g += sep + _with_sidecars(mask)
                globs.append(g)
            if not globs:
                continue
            body = "\n".join(f"       {g}" for g in sorted(set(globs)))
            docs.append(f"""name: Custom.CPF.Collect.{os_name.capitalize()}
description: |
   Collect the files Connected Phone Forensics parses (phone-to-computer artifacts) from a {os_name} system.
   Generated by 'cpf targets --format velociraptor'.
parameters:
  - name: collectionSpec
    type: csv
    default: |
       Glob
{body}
  - name: Root
    default: "{root}"
sources:
  - query: |
      SELECT * FROM Artifact.Generic.Collectors.File(collectionSpec=collectionSpec, Root=Root)
""")
        return "\n---\n".join(docs)
    raise ValueError(fmt)


def render_docs() -> str:
    plugins = list(load_plugins().values())
    lines = [
        "# Connected Phone Forensics artifact reference",
        "",
        "Generated from plugin metadata by `cpf docs`. Each entry lists the paths read,",
        "the channel, the validation level and the public references the parser is based on.",
        "",
        "| Parser | Computer OS | Channel | Validation |",
        "|---|---|---|---|",
    ]
    for cls in sorted(plugins, key=lambda c: (c.os, c.id)):
        lines.append(f"| [`{cls.id}`](#{cls.id.replace('_', '-')}) | {cls.os} | {cls.channel.value} "
                     f"| {cls.validation.value} |")
    for cls in sorted(plugins, key=lambda c: (c.os, c.id)):
        lines += ["", f"## {cls.id}", "", f"**{cls.name}**", "", cls.description.strip(), "",
                  "Paths:", ""]
        lines += [f"- `{p}`" for p in cls.paths]
        if cls.references:
            lines += ["", "References:", ""]
            lines += [f"- {r}" for r in cls.references]
    return "\n".join(lines) + "\n"
